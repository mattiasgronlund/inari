(** The axioms that the theorems depend on. [make] fails if this prints
    any axiom that is not listed in [AXIOMS] in the [Makefile].

    The [Example]s of [MpfrExamples.v] are not printed: each one applies a
    theorem printed here, or a constructor of [made] or [dmade], of which
    [made_valid] is printed here, to [ideal emin emax] and to proofs that
    the tactic [mpfr_example] builds from [range_ok] and [ideal_mpfr_ok],
    which is printed here too. At the end, two [Search]es write the names
    from which [make] takes those that must have an [Example] there.

    The files about the limbs of [Nat] and the dyadic kernel, from
    [Limbs.v] to [DyDriver.v], and those about the kernel's constants and
    its exponential and hyperbolic functions, [DyConst.v], [DyExp.v],
    [DyHyp.v], those about its logarithms, [DyLog.v] and [DyLogHyp.v],
    those about π and its inverse trigonometric functions, [DyConstPi.v],
    [DyAtan.v] and [DyAsin.v], the one about its trigonometric functions,
    [DyTrig.v], those about its powers, [DyPown.v] and [DyPow.v], those
    about its functions rounded to nearest, from [DyDriverNear.v] to
    [DyPowNear.v], the one about the signs of [pow] in [src/cr.rs],
    [CrPow.v], those about its roots and the square roots of
    [src/cr.rs], from [RootReal.v] to [CrRoot.v], and [DyPoint.v] and
    [DyPointDec.v], are required
    without being imported, as
    some of their names, such as [add_correct], are those of other
    theorems printed here, and their theorems are printed by qualified
    name. None of them quantifies over an MPFR. The files about the cap
    of Ziv's strategy, [KahanMcDonald.v], [DyTrigPos.v], [SideTight.v],
    [SideTheorems.v] and [DyPointSide.v], and those about the exact
    results of the kernel's functions, from [ExpQuadratic.v] to
    [DyAtanExact.v], are required the same way. [exp_not_quadratic] of
    [ExpQuadratic.v] is a definition, a premise of the four theorems for
    [sinh], [cosh], [asinh] and [acosh] and of their forms with a driver,
    so the lines below do not print it. *)

